"""
Regenerates Vectors.cs: known-good outputs of pyatv (the reference AirPlay implementation) and srptools for fixed inputs,
which the C# crypto and framing must reproduce byte for byte. Needs a venv with pyatv and srptools:
    python3 -m venv tmp/airplay-venv && tmp/airplay-venv/bin/pip install pyatv==0.17.0 'srptools<2'
    tmp/airplay-venv/bin/python libs/airplay-tests/Vectors/make_vectors.py > libs/airplay-tests/Vectors/Vectors.cs
"""
import hashlib
import plistlib

from srptools import SRPClientSession, SRPContext, constants

from pyatv.auth.hap_session import HAPSession
from pyatv.auth.hap_srp import hkdf_expand
from pyatv.auth.hap_tlv8 import write_tlv
from pyatv.support import chacha20


def hx(b):
    return b.hex()


out = []


def const(name, value):
    out.append(f'    public const string {name} = "{value}";')


# TLV8: a short value and one that continues across two fragments
tlv = write_tlv({1: b"abc", 3: bytes(i % 251 for i in range(300)), 6: b"\x05"})
const("Tlv", hx(tlv))

# HKDF
shared = bytes(range(32))
const("HkdfShared", hx(shared))
const("HkdfControlWrite", hx(hkdf_expand("Control-Salt", "Control-Write-Encryption-Key", shared)))
const("HkdfPairSetup", hx(hkdf_expand("Pair-Setup-Encrypt-Salt", "Pair-Setup-Encrypt-Info", shared)))

# HAP framing, 2500 bytes (three frames) each way
key_a, key_b = bytes([1] * 32), bytes([2] * 32)
plain = bytes(i % 256 for i in range(2500))
sender = HAPSession()
sender.enable(key_a, key_b)
const("FramePlain", hx(plain))
const("FrameEncrypted", hx(sender.encrypt(plain) + sender.encrypt(b"second message")))
# What the receiver sends us: encrypted with key_b as its output.
receiver = HAPSession()
receiver.enable(key_b, key_a)
const("FrameFromReceiver", hx(receiver.encrypt(plain)))

# Pairing messages: nonce is the message name, zero padded
cipher = chacha20.Chacha20Cipher8byteNonce(key_a, key_a)
const("SealedMessage", hx(cipher.encrypt(b"pairing payload", nonce="PS-Msg05".encode())))

# SRP with fixed private key, salt and receiver public key
N = int(constants.PRIME_3072, 16)
a = bytes(range(1, 33))
salt = bytes(range(100, 116))
b_public = pow(5, int.from_bytes(hashlib.sha512(b"receiver").digest() * 6, "big"), N)
b_bytes = b_public.to_bytes(384, "big")
context = SRPContext("Pair-Setup", "1234", prime=constants.PRIME_3072, generator=constants.PRIME_3072_GEN, hash_func=hashlib.sha512)
session = SRPClientSession(context, a.hex())
session.process(b_bytes.hex(), salt.hex())
const("SrpPrivate", hx(a))
const("SrpSalt", hx(salt))
const("SrpReceiverPublic", hx(b_bytes))
const("SrpPublic", session.public)
const("SrpKey", session.key.decode())
const("SrpProof", session.key_proof.decode())

# A property list the receiver might send
sample = {
    "eventPort": 53112,
    "name": "Living room",
    "unicode": "Café ☕",
    "ratio": 1.5,
    "yes": True,
    "no": False,
    "negative": -7,
    "big": 2**40,
    "blob": bytes(range(20)),
    "streams": [{"streamID": 3, "type": 130}, "x"],
}
const("Plist", hx(plistlib.dumps(sample, fmt=plistlib.FMT_BINARY)))

print("// Generated by make_vectors.py from pyatv and srptools; do not edit.")
print("namespace HomeyDash.AirPlay.Tests;")
print()
print("internal static class Vectors")
print("{")
print("\n".join(out))
print("}")
